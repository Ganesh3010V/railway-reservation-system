-- CATEGORY 6: DATABASE VIEWS
-- =====================================================================

-- VIEW 6.1: Create a reusable view for the Train Conductor (TTE Manifest)
DROP VIEW IF EXISTS vw_PassengerManifest;

CREATE VIEW vw_PassengerManifest AS
SELECT 
    b.PNR,
    p.Name AS PassengerName,
    p.Age,
    p.Gender,
    p.Contact,
    t.TrainNo,
    t.TrainName,
    sc.ClassType,
    s.CoachNo,
    s.SeatNo,
    b.BoardingStation,
    b.ExitStation,
    b.JourneyDate,
    b.Status AS BookingStatus
FROM Booking b
JOIN Passenger p  ON b.PassengerID = p.PassengerID
JOIN Train t      ON b.TrainNo = t.TrainNo
JOIN SeatClass sc ON b.ClassID = sc.ClassID
LEFT JOIN Seat s  ON b.SeatID = s.SeatID;

-- Query the created view:
SELECT * FROM vw_PassengerManifest WHERE BookingStatus = 'Confirmed';


