-- =====================================================================
-- CATEGORY 1: SELECTION, PROJECTION & PATTERN MATCHING
-- =====================================================================

-- QUERY 1.1: Retrieve all passengers aged 30 or above, ordered by Age descending.
-- Concept: SELECT, WHERE, ORDER BY DESC
SELECT 
    PassengerID, 
    Name, 
    Age, 
    Gender, 
    Contact
FROM Passenger
WHERE Age >= 30
ORDER BY Age DESC;


-- QUERY 1.2: Find all passengers whose name starts with 'S' or contains 'Kumar'.
-- Concept: Pattern Matching using LIKE and OR operator
SELECT 
    PassengerID, 
    Name, 
    Age, 
    Gender, 
    Contact
FROM Passenger
WHERE Name LIKE 'S%' OR Name LIKE '%Kumar%'
ORDER BY Name ASC;


-- =====================================================================
-- CATEGORY 2: COMPLEX MULTI-TABLE JOINS (INNER & LEFT JOIN)
-- =====================================================================

-- QUERY 2.1: Retrieve all Train routes with Station sequence and cumulative distance.
-- Concept: 3-Table JOIN (Train + RouteStation + Station)
SELECT 
    t.TrainNo,
    t.TrainName,
    rs.SeqNo AS StopOrder,
    rs.StationCode,
    s.StationName,
    s.City,
    rs.DistanceFromOrigin AS KmFromOrigin
FROM Train t
JOIN RouteStation rs ON t.TrainNo = rs.TrainNo
JOIN Station s       ON rs.StationCode = s.StationCode
ORDER BY t.TrainNo, rs.SeqNo ASC;


-- QUERY 2.2: Official Confirmed Passenger Reservation Chart (TTE Manifest).
-- Concept: 5-Table INNER JOIN (Booking + Passenger + Train + SeatClass + Seat)
SELECT 
    b.PNR,
    p.Name AS PassengerName,
    CONCAT(p.Age, ' / ', p.Gender) AS Age_Sex,
    t.TrainName,
    sc.ClassType,
    s.CoachNo,
    s.SeatNo,
    CONCAT(b.BoardingStation, ' -> ', b.ExitStation) AS JourneyRoute,
    b.JourneyDate,
    b.Status
FROM Booking b
JOIN Passenger p  ON b.PassengerID = p.PassengerID
JOIN Train t      ON b.TrainNo = t.TrainNo
JOIN SeatClass sc ON b.ClassID = sc.ClassID
JOIN Seat s       ON b.SeatID = s.SeatID
WHERE b.Status = 'Confirmed'
ORDER BY t.TrainNo, s.CoachNo, s.SeatNo;


-- QUERY 2.3: Retrieve all Bookings including physical seat details if allocated,
--            or display 'Waitlisted / No Seat' if unallocated.
-- Concept: LEFT OUTER JOIN
SELECT 
    b.PNR,
    p.Name AS PassengerName,
    t.TrainName,
    sc.ClassType,
    COALESCE(s.CoachNo, 'N/A') AS CoachNo,
    COALESCE(CAST(s.SeatNo AS CHAR), 'WAITLIST') AS SeatNumber,
    b.Status
FROM Booking b
JOIN Passenger p    ON b.PassengerID = p.PassengerID
JOIN Train t        ON b.TrainNo = t.TrainNo
JOIN SeatClass sc   ON b.ClassID = sc.ClassID
LEFT JOIN Seat s    ON b.SeatID = s.SeatID
ORDER BY b.PNR ASC;


-- =====================================================================
-- CATEGORY 3: AGGREGATE FUNCTIONS, GROUP BY & HAVING
-- =====================================================================

-- QUERY 3.1: Calculate overall financial statistics from successful ticket payments.
-- Concept: Aggregate functions (SUM, AVG, MAX, MIN, COUNT)
SELECT 
    COUNT(PaymentID)      AS TotalTransactions,
    SUM(Amount)           AS TotalRevenueCollected,
    AVG(Amount)           AS AverageTicketFare,
    MAX(Amount)           AS MaximumFarePaid,
    MIN(Amount)           AS MinimumFarePaid
FROM Payment
WHERE Status = 'Success';


-- QUERY 3.2: Revenue and total bookings generated by each Train.
-- Concept: GROUP BY with Multi-Table Aggregate & COALESCE
SELECT 
    t.TrainNo,
    t.TrainName,
    COUNT(DISTINCT b.PNR)        AS TotalBookings,
    COALESCE(SUM(py.Amount), 0)  AS TotalRevenue
FROM Train t
LEFT JOIN Booking b  ON t.TrainNo = b.TrainNo
LEFT JOIN Payment py ON b.PNR = py.PNR AND py.Status = 'Success'
GROUP BY t.TrainNo, t.TrainName
ORDER BY TotalRevenue DESC;


-- QUERY 3.3: Find Trains that have 2 or more confirmed reservations.
-- Concept: GROUP BY with HAVING clause filtering on aggregated counts
SELECT 
    t.TrainNo,
    t.TrainName,
    COUNT(b.PNR) AS ConfirmedCount
FROM Train t
JOIN Booking b ON t.TrainNo = b.TrainNo
WHERE b.Status = 'Confirmed'
GROUP BY t.TrainNo, t.TrainName
HAVING COUNT(b.PNR) >= 2;


-- =====================================================================
-- CATEGORY 4: NESTED SUBQUERIES & CORRELATED SUBQUERIES
-- =====================================================================

-- QUERY 4.1: Retrieve passengers who are currently placed on the Waiting List.
-- Concept: Nested Subquery using IN operator
SELECT 
    PassengerID, 
    Name, 
    Contact 
FROM Passenger
WHERE PassengerID IN (
    SELECT PassengerID 
    FROM Booking 
    WHERE Status = 'Waitlisted'
);


-- QUERY 4.2: Retrieve confirmed passengers who have NOT yet completed payment.
-- Concept: Subquery using NOT IN
SELECT 
    b.PNR,
    p.Name AS PassengerName,
    b.TrainNo,
    b.BoardingStation,
    b.ExitStation
FROM Booking b
JOIN Passenger p ON b.PassengerID = p.PassengerID
WHERE b.Status = 'Confirmed'
  AND b.PNR NOT IN (
      SELECT PNR 
      FROM Payment 
      WHERE Status = 'Success'
  );


-- QUERY 4.3: Find all Trains that currently have active waitlisted passengers.
-- Concept: Correlated Subquery using EXISTS
SELECT 
    t.TrainNo, 
    t.TrainName, 
    t.Source, 
    t.Destination
FROM Train t
WHERE EXISTS (
    SELECT 1 
    FROM Booking b 
    WHERE b.TrainNo = t.TrainNo 
      AND b.Status = 'Waitlisted'
);


-- =====================================================================
-- CATEGORY 5: CONDITIONAL LOGIC & ADVANCED AGGREGATION
-- =====================================================================

-- QUERY 5.1: Reservation Status Matrix per Train (Confirmed, Waitlist, Cancelled).
-- Concept: Conditional Aggregation using CASE WHEN inside SUM()
SELECT 
    t.TrainNo,
    t.TrainName,
    SUM(CASE WHEN b.Status = 'Confirmed'  THEN 1 ELSE 0 END) AS ConfirmedBookings,
    SUM(CASE WHEN b.Status = 'Waitlisted' THEN 1 ELSE 0 END) AS WaitlistBookings,
    SUM(CASE WHEN b.Status = 'Cancelled'  THEN 1 ELSE 0 END) AS CancelledBookings,
    COUNT(b.PNR) AS TotalReservations
FROM Train t
LEFT JOIN Booking b ON t.TrainNo = b.TrainNo
GROUP BY t.TrainNo, t.TrainName;


-- QUERY 5.2: Physical Seat Availability Matrix per Coach.
-- Concept: Seat status grouping and physical capacity utilization
SELECT 
    sc.TrainNo,
    sc.ClassType,
    s.CoachNo,
    COUNT(s.SeatID)                                        AS TotalCapacity,
    SUM(CASE WHEN s.Status = 'Occupied'  THEN 1 ELSE 0 END) AS OccupiedSeats,
    SUM(CASE WHEN s.Status = 'Available' THEN 1 ELSE 0 END) AS AvailableSeats,
    ROUND((SUM(CASE WHEN s.Status = 'Occupied' THEN 1 ELSE 0 END) / COUNT(s.SeatID)) * 100, 1) AS OccupancyPercentage
FROM Seat s
JOIN SeatClass sc ON s.ClassID = sc.ClassID
GROUP BY sc.TrainNo, sc.ClassType, s.CoachNo;


